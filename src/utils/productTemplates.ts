export interface DefaultProductTemplateDef {
  id: string;
  name: string;
  categoryId: string;
  brandId: string;
  variant: string;
  originType?: OriginType;
  baseUnit: string;
  defaultPurchaseUnit?: string;
  defaultSaleUnit?: string;
  packagingUnits?: ProductTemplatePackaging[];
  hasUnconfirmedPackaging?: boolean;
  suggestedPurchasePrice?: number;
  suggestedSalePrice?: number;
  suggestedWholesalePrice?: number;
  priceSource?: string;
  priceUpdatedAt?: string;
  trackExpiry?: boolean;
  bottleSize?: string;
  storageLocation?: string;
  isReturnable?: boolean;
  returnableUnitName?: string;
  searchKeywords?: string[];
}

function packPkg(
  unitName: string,
  containsQty: number,
  parentUnitName: string,
  options?: {
    conversionQty?: number;
    allowPurchase?: boolean;
    allowSale?: boolean;
    isDefaultPurchase?: boolean;
    isDefaultSale?: boolean;
    needsConfirmation?: boolean;
  }
): ProductTemplatePackaging {
  return {
    unitName,
    containsQty,
    parentUnitName,
    conversionQty: options?.conversionQty ?? containsQty,
    allowPurchase: options?.allowPurchase ?? true,
    allowSale: options?.allowSale ?? true,
    isDefaultPurchase: options?.isDefaultPurchase ?? false,
    isDefaultSale: options?.isDefaultSale ?? false,
    needsConfirmation: options?.needsConfirmation ?? false,
  };
}

